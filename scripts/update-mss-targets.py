#!/usr/bin/env python3
"""Regenerate config/mss_targets.txt from config/domains.txt via DNS-over-HTTPS.

The MSS-clamp engine accepts only explicit IPv4/IPv6 literals; it rejects
domains and CIDR. This script resolves the default domains through DoH
(dns.google, fallback cloudflare-dns.com), deduplicates and caps the list.
It is a snapshot: CDN addresses rotate, and shared addresses may affect more
than one site. MSS-clamp is disabled by default; these targets are inert until
it is enabled.
"""
import argparse
import datetime
import ipaddress
import json
import pathlib
import sys
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_DOMAINS = ROOT / "config" / "domains.txt"
DEFAULT_OUT = ROOT / "config" / "mss_targets.txt"
DOH = [
    "https://dns.google/resolve?name={q}&type={t}",
    "https://cloudflare-dns.com/dns-query?name={q}&type={t}",
]


def doh(name: str, rrtype: str):
    q = urllib.parse.quote(name)
    for tmpl in DOH:
        url = tmpl.format(q=q, t=rrtype)
        try:
            req = urllib.request.Request(url, headers={"Accept": "application/dns-json"})
            with urllib.request.urlopen(req, timeout=8) as r:
                data = json.loads(r.read().decode())
            out = []
            for ans in data.get("Answer", []):
                if ans.get("type") in (1, 28):
                    out.append(ans["data"])
            return out
        except Exception:
            continue
    return []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--domains", default=str(DEFAULT_DOMAINS))
    ap.add_argument("--output", default=str(DEFAULT_OUT))
    ap.add_argument("--max-per-family", type=int, default=256)
    args = ap.parse_args()

    domains = []
    for line in pathlib.Path(args.domains).read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            domains.append(line)

    v4, v6 = set(), set()
    missing = []
    for d in domains:
        found = False
        for rr in ("A", "AAAA"):
            for raw in doh(d, rr):
                try:
                    ip = ipaddress.ip_address(raw)
                except ValueError:
                    continue
                (v4 if ip.version == 4 else v6).add(ip)
                found = True
        if not found:
            missing.append(d)
        print(f"{d}: {len(v4)} v4, {len(v6)} v6 cumulative", flush=True)

    v4s = [str(x) for x in sorted(v4)][: args.max_per_family]
    v6s = [str(x) for x in sorted(v6)][: args.max_per_family]
    stamp = datetime.date.today().isoformat()
    header = f"""# Mutekizu / mutekizu MSS-clamp targets.
# Snapshot generated by scripts/update-mss-targets.py on {stamp}.
# Source domains: {pathlib.Path(args.domains).name}; resolved via DoH.
#
# MSS-clamp is DISABLED by default (mss_clamp=false); this list is inert until
# it is enabled. Explicit IPv4/IPv6 only: the engine rejects domains and CIDR.
# Addresses rotate; refresh with the script. A shared CDN address may affect
# several sites, and MSS-clamp applies to the whole upload direction.
#
# IPv4 targets ({len(v4s)}):
"""
    body = "\n".join(v4s) + ("\n" if v4s else "")
    body += f"\n# IPv6 targets ({len(v6s)}):\n" + "\n".join(v6s) + ("\n" if v6s else "")
    pathlib.Path(args.output).write_text(header + body)
    print(f"wrote {args.output}: {len(v4s)} IPv4, {len(v6s)} IPv6")
    if missing:
        print("no addresses for: " + ", ".join(missing), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

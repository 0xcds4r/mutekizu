std::string render_ruleset(const Config& cfg, const AddressSet& mss_targets)
{
    IpFragTargets ipfrag;
    if (cfg.ip_frag_enabled) {
        std::string ferr;
        (void)load_ipfrag_targets(cfg.ip_frag_targets_file, ipfrag, ferr);
    }

    std::ostringstream os;
    os << "# generated by mutekizu; this file contains only our own table\n"
       << "table inet " << kTableName << " {\n"
       << "  comment \"" << kOwnerComment << "\"\n";

    if (cfg.ip_frag_enabled && !ipfrag.v4.empty()) {
        os << "  set ipfrag4 { type ipv4_addr; flags interval; size 4096; elements = { ";
        for (std::size_t i = 0; i < ipfrag.v4.size(); ++i) {
            if (i != 0) os << ", ";
            os << ipfrag.v4[i];
        }
        os << " } }\n";
    }
    if (cfg.ip_frag_enabled && !ipfrag.v6.empty()) {
        os << "  set ipfrag6 { type ipv6_addr; flags interval; size 4096; elements = { ";
        for (std::size_t i = 0; i < ipfrag.v6.size(); ++i) {
            if (i != 0) os << ", ";
            os << ipfrag.v6[i];
        }
        os << " } }\n";
    }

    const bool mss4 = cfg.mss_clamp && cfg.enable_ipv4 && !mss_targets.v4.empty();
    const bool mss6 = cfg.mss_clamp && cfg.enable_ipv6 && !mss_targets.v6.empty();

    if (mss4 || mss6) {
        if (mss4) {
            os << "  set mss4 { type ipv4_addr; size 256; elements = { ";
            for (std::size_t i = 0; i < mss_targets.v4.size(); ++i) {
                if (i != 0) os << ", ";
                os << mss_targets.v4[i];
            }
            os << " } }\n";
        }
        if (mss6) {
            os << "  set mss6 { type ipv6_addr; size 256; elements = { ";
            for (std::size_t i = 0; i < mss_targets.v6.size(); ++i) {
                if (i != 0) os << ", ";
                os << mss_targets.v6[i];
            }
            os << " } }\n";
        }
        os << "  chain input {\n"
           << "    type filter hook input priority -150; policy accept;\n";
        if (mss4) {
            os << "    meta l4proto tcp ct direction reply ct original ip daddr @mss4 "
               << "ct original proto-dst { " << port_set(cfg) << " } "
               << "tcp flags & (syn|ack|rst|fin) == (syn|ack) "
               << "tcp option maxseg size > " << cfg.mss_value
               << " counter tcp option maxseg size set " << cfg.mss_value << "\n";
        }
        if (mss6) {
            os << "    meta l4proto tcp ct direction reply ct original ip6 daddr @mss6 "
               << "ct original proto-dst { " << port_set(cfg) << " } "
               << "tcp flags & (syn|ack|rst|fin) == (syn|ack) "
               << "tcp option maxseg size > " << cfg.mss_value
               << " counter tcp option maxseg size set " << cfg.mss_value << "\n";
        }
        os << "  }\n";
    }

    if (cfg.split_enabled) {
        os << "  chain " << kChainName << " {\n"
           << "    type filter hook output priority -150; policy accept;\n"
           << "    meta mark != " << hex32(cfg.fwmark) << " ";
        if (cfg.enable_ipv4 && !ipfrag.v4.empty()) os << "ip daddr != @ipfrag4 ";
        if (cfg.enable_ipv6 && !ipfrag.v6.empty()) os << "ip6 daddr != @ipfrag6 ";

        if (cfg.enable_ipv4 && !cfg.enable_ipv6)
            os << "meta nfproto ipv4 ";
        else if (!cfg.enable_ipv4 && cfg.enable_ipv6)
            os << "meta nfproto ipv6 ";

        os << "tcp dport " << port_set(cfg)
           << " ct original packets 0-" << cfg.inspect_packets
           << " queue num " << cfg.queue_num << " bypass"
           << " comment \"" << kQueueComment << "\"\n"
           << "  }\n";
    }

    if (cfg.reply_observe) {
        os << "  chain " << kReplyChainName << " {\n"
           << "    type filter hook input priority -150; policy accept;\n"
           << "    meta mark != " << hex32(cfg.fwmark) << " ";
        if (cfg.enable_ipv4 && !cfg.enable_ipv6)
            os << "meta nfproto ipv4 ";
        else if (!cfg.enable_ipv4 && cfg.enable_ipv6)
            os << "meta nfproto ipv6 ";
        os << "tcp sport " << port_set(cfg)
           << " ct reply packets 0-" << cfg.reply_inspect_packets
           << " queue num " << cfg.reply_queue_num << " bypass"
           << " comment \"" << kQueueComment << "-reply\"\n"
           << "  }\n";
    }

    if (cfg.ip_frag_enabled && !ipfrag.empty()) {
        std::ostringstream ports;
        for (std::size_t i = 0; i < cfg.ip_frag_ports.size(); ++i) {
            if (i != 0) ports << ", ";
            ports << cfg.ip_frag_ports[i];
        }
        os << "  chain ipfrag {\n"
           << "    type filter hook output priority -150; policy accept;\n"
           << "    meta mark != " << hex32(cfg.fwmark) << " ";
        if (cfg.enable_ipv4 && !ipfrag.v4.empty())
            os << "ip daddr @ipfrag4 tcp dport { " << ports.str()
               << " } ct original packets 0-" << cfg.ip_frag_inspect_packets
               << " queue num " << cfg.ip_frag_queue_num << " bypass"
               << " comment \"" << kQueueComment << "-ipfrag\"\n";
        if (cfg.enable_ipv6 && !ipfrag.v6.empty())
            os << "    ip6 daddr @ipfrag6 tcp dport { " << ports.str()
               << " } ct original packets 0-" << cfg.ip_frag_inspect_packets
               << " queue num " << cfg.ip_frag_queue_num << " bypass"
               << " comment \"" << kQueueComment << "-ipfrag6\"\n";
        os << "  }\n";
    }

    if (cfg.udp_fake_enabled) {
        os << "  chain " << kUdpChainName << " {\n"
           << "    type filter hook output priority -150; policy accept;\n"
           << "    meta mark != " << hex32(cfg.fwmark) << " ";
        if (cfg.enable_ipv4 && !cfg.enable_ipv6)
            os << "meta nfproto ipv4 ";
        else if (!cfg.enable_ipv4 && cfg.enable_ipv6)
            os << "meta nfproto ipv6 ";
        os << "udp dport { 443, 19294-19344, 50000-50100 } "
           << "ct original packets 0-" << cfg.inspect_packets
           << " queue num " << cfg.queue_num << " bypass"
           << " comment \"" << kQueueComment << "-udp\"\n"
           << "  }\n";
    }

    os << "}\n";
    return os.str();
}

bool nft_available(std::string& version)
{
    CmdResult r;
    std::string err;
    if (!nft_cmd({"--version"}, r, err)) return false;
    if (r.exit_code != 0) return false;
    version = r.output;
    while (!version.empty() && (version.back() == '\n' || version.back() == '\r'))
        version.pop_back();
    return true;
}

TableState nft_table_exists(std::string& error)
{
    CmdResult r;
    if (!nft_cmd({"list", "table", "inet", kTableName}, r, error))
        return TableState::Unknown;
    if (r.exit_code == 0) return TableState::Present;
    // nft returns != 0 both for "no such table" and for permission errors.
    if (r.output.find("No such file") != std::string::npos ||
        r.output.find("does not exist") != std::string::npos)
        return TableState::Absent;
    error = r.output;
    return TableState::Unknown;
}

bool table_owned(std::string& error)
{
    CmdResult r;
    if (!nft_cmd({"-nn", "list", "table", "inet", kTableName}, r, error)) return false;
    if (r.exit_code != 0) {
        error = "cannot inspect table inet " + std::string(kTableName);
        return false;
    }
    const std::string marker = std::string("comment \"") + kOwnerComment + "\"";
    const auto brace = r.output.find('{');
    const auto comment = r.output.find(marker);
    if (brace == std::string::npos || comment == std::string::npos) {
        error = "table inet " + std::string(kTableName) +
                " exists but has no mutekizu owner comment; refusing to touch it";
        return false;
    }
    // The owner comment must belong to the table itself, before any child object.
    const std::string between = r.output.substr(brace + 1, comment - brace - 1);
    if (between.find_first_not_of(" \t\r\n") != std::string::npos) {
        error = "table inet " + std::string(kTableName) +
                " owner comment mismatch; refusing to touch it";
        return false;
    }
    return true;
}

bool rules_show(std::string& output, std::string& error)
{
    CmdResult r;
    if (!nft_cmd({"list", "table", "inet", kTableName}, r, error)) return false;
    output = r.output;
    return r.exit_code == 0;
}

bool rules_remove(bool dry_run, std::string& error)
{
    std::string exists_err;
    const TableState st = nft_table_exists(exists_err);
    if (st == TableState::Absent) return true;
    if (st == TableState::Unknown) {
        if (dry_run) {
            std::fprintf(stdout, "[dry-run] cannot inspect table inet %s: %s\n",
                         kTableName, exists_err.c_str());
            return true;
        }
        error = "cannot determine whether table inet " + std::string(kTableName) +
                " exists: " + exists_err;
        return false;
    }
    std::string own_err;
    if (!table_owned(own_err)) {
        error = own_err;
        return false;
    }

    if (dry_run) {
        std::fprintf(stdout, "[dry-run] %s delete table inet %s\n", kNftBinary, kTableName);
        return true;
    }
    CmdResult r;
    if (!nft_cmd({"delete", "table", "inet", kTableName}, r, error)) return false;
    if (r.exit_code != 0) {
        error = "nft delete table failed: " + r.output;
        return false;
    }
    return true;
}

bool rules_apply(const Config& cfg, const AddressSet& mss_targets, bool dry_run,
                 std::string& error)
{
    const std::string content = render_ruleset(cfg, mss_targets);

    std::string path;
    if (!write_temp_file(content, path, error)) return false;

    CmdResult check;
    if (!nft_cmd({"-c", "-f", path}, check, error)) {
        ::unlink(path.c_str());
        return false;
    }
    if (check.exit_code != 0) {
        const bool perm = check.output.find("Operation not permitted") != std::string::npos;
        if (!perm) {
            error = "nft syntax check failed:\n" + check.output;
            ::unlink(path.c_str());
            return false;
        }
        std::fprintf(stdout,
                     "note: nft syntax check needs CAP_NET_ADMIN; skipped (no changes made)\n");
    }

    if (dry_run) {
        std::fprintf(stdout, "[dry-run] planned ruleset:\n%s\n", content.c_str());
        std::string probe_err;
        if (nft_table_exists(probe_err) == TableState::Present) {
            if (!table_owned(probe_err)) {
                error = probe_err;
                ::unlink(path.c_str());
                return false;
            }
            std::fprintf(stdout, "[dry-run] will first delete existing table inet %s\n", kTableName);
        }
        std::fprintf(stdout, "[dry-run] %s -f %s\n", kNftBinary, path.c_str());
        ::unlink(path.c_str());
        return true;
    }

    // Removing our own table first makes restart idempotent. It is safe because
    // the queue is already bound by the caller (and has `bypass`).
    std::string own_err;
    const TableState existing = nft_table_exists(own_err);
    if (existing == TableState::Present && !table_owned(own_err)) {
        error = own_err;
        ::unlink(path.c_str());
        return false;
    }
    if (existing == TableState::Unknown) {
        error = "cannot inspect existing table: " + own_err;
        ::unlink(path.c_str());
        return false;
    }

    CmdResult del;
    std::string ignored;
    if (nft_cmd({"delete", "table", "inet", kTableName}, del, ignored) &&
        del.exit_code != 0 && nft_table_exists(ignored) == TableState::Present) {
        error = "cannot remove existing table inet " + std::string(kTableName) + ": " + del.output;
        ::unlink(path.c_str());
        return false;
    }

    CmdResult apply;
    if (!nft_cmd({"-f", path}, apply, error)) {
        ::unlink(path.c_str());
        return false;
    }
    ::unlink(path.c_str());
    if (apply.exit_code != 0) {
        error = "nft apply failed:\n" + apply.output;
        return false;
    }
    return true;
}


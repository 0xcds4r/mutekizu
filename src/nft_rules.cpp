constexpr const char* kNftBinary = "/usr/bin/nft";
constexpr const char* kOwnerComment = "mutekizu-v1";
constexpr const char* kUdpChainName = "udp_output";
constexpr const char* kReplyChainName = "reply";

std::string hex32(std::uint32_t v)
{
    std::ostringstream os;
    os << "0x" << std::hex << v;
    return os.str();
}

std::string port_set(const Config& cfg)
{
    std::ostringstream os;
    if (cfg.ports.size() == 1) {
        os << cfg.ports.front();
    } else {
        os << "{ ";
        for (std::size_t i = 0; i < cfg.ports.size(); ++i) {
            if (i != 0) os << ", ";
            os << cfg.ports[i];
        }
        os << " }";
    }
    return os.str();
}

bool write_temp_file(const std::string& content, std::string& path, std::string& error)
{
    const char* dirs[] = {"/run/mutekizu", "/tmp"};
    int fd = -1;
    for (const char* d : dirs) {
        if (::access(d, W_OK) != 0) continue;
        std::string tmpl = std::string(d) + "/mutekizu-rules-XXXXXX";
        std::vector<char> buf(tmpl.begin(), tmpl.end());
        buf.push_back('\0');
        fd = ::mkstemp(buf.data());
        if (fd >= 0) {
            path.assign(buf.data());
            break;
        }
    }
    if (fd < 0) {
        error = std::string("cannot create temporary rules file: ") + std::strerror(errno);
        return false;
    }

    std::size_t off = 0;
    while (off < content.size()) {
        const ssize_t n = ::write(fd, content.data() + off, content.size() - off);
        if (n < 0) {
            if (errno == EINTR) continue;
            error = std::string("write rules file: ") + std::strerror(errno);
            ::close(fd);
            ::unlink(path.c_str());
            return false;
        }
        off += static_cast<std::size_t>(n);
    }
    ::close(fd);
    return true;
}

bool nft_cmd(const std::vector<std::string>& extra, CmdResult& res, std::string& error)
{
    std::vector<std::string> argv{kNftBinary};
    argv.insert(argv.end(), extra.begin(), extra.end());
    return run_command(argv, res, error);
}

